-- VidaActiva: esquema inicial y controles de acceso.
-- La existencia se modifica únicamente al verificar el pago del pedido.

create extension if not exists pgcrypto;
create schema if not exists private;

create table if not exists public.products (
 id text primary key,
 category text not null default '',
 product_name text not null,
 presentation_lab text not null default '',
 base_price numeric not null check(base_price>=0),
 description text not null default '',
 image_file text,
 slug text not null unique,
 active boolean not null default true,
 stock integer not null default 0 check(stock>=0),
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now()
);
create table if not exists public.orders (
 id uuid primary key default gen_random_uuid(),
 order_number bigint generated by default as identity unique,
 status text not null default 'pending_payment' check(status in ('pending_payment','payment_under_review','paid_confirmed','payment_rejected','cancelled','stock_issue')),
 customer_name text not null,
 customer_phone text not null,
 customer_email text,
 customer_address text,
 notes text,
 subtotal numeric not null check(subtotal>=0),
 total numeric not null check(total>=0),
 currency text not null default 'USD',
 idempotency_key uuid not null unique,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now(),
 confirmed_at timestamptz
);
create table if not exists public.order_items (
 id bigint generated by default as identity primary key,
 order_id uuid not null references public.orders(id) on delete cascade,
 product_id text not null references public.products(id),
 product_name text not null,
 quantity integer not null check(quantity>0),
 unit_price numeric not null check(unit_price>=0),
 line_total numeric not null check(line_total>=0)
);
create table if not exists public.payments (
 id uuid primary key default gen_random_uuid(),
 order_id uuid not null references public.orders(id) on delete cascade,
 method text not null default 'manual',
 reference text,
 proof_url text,
 status text not null default 'submitted' check(status in ('submitted','verified','rejected')),
 reviewed_by uuid references auth.users(id),
 reviewed_at timestamptz,
 created_at timestamptz not null default now()
);
create table if not exists public.stock_movements (
 id bigint generated by default as identity primary key,
 product_id text not null references public.products(id),
 order_id uuid references public.orders(id),
 movement_type text not null check(movement_type in ('initial','restock','sale','adjustment','reversal')),
 quantity_change integer not null,
 stock_after integer not null check(stock_after>=0),
 note text,
 created_by uuid references auth.users(id),
 created_at timestamptz not null default now()
);
create table if not exists public.admin_users (
 user_id uuid primary key references auth.users(id) on delete cascade,
 role text not null default 'admin' check(role in ('admin','manager')),
 created_at timestamptz not null default now()
);
create table if not exists public.coupons (
 code text primary key,
 discount_percent numeric not null check(discount_percent>0 and discount_percent<=100),
 active boolean not null default true,
 expires_at timestamptz,
 created_at timestamptz not null default now()
);

alter table public.products enable row level security;
