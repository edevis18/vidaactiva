alter table public.payments enable row level security;
alter table public.stock_movements enable row level security;
alter table public.admin_users enable row level security;
alter table public.coupons enable row level security;

create or replace function private.is_admin()
returns boolean language sql stable security definer set search_path=''
as $$ select exists(select 1 from public.admin_users a where a.user_id=(select auth.uid())); $$;
revoke all on function private.is_admin() from public,anon;
grant usage on schema private to authenticated;
grant execute on function private.is_admin() to authenticated;

drop policy if exists "Public can read active products" on public.products;
create policy "Public can read active products" on public.products for select to anon,authenticated using(active);
drop policy if exists "Admins manage products" on public.products;
create policy "Admins manage products" on public.products for all to authenticated using((select private.is_admin())) with check((select private.is_admin()));
drop policy if exists "Admins manage orders" on public.orders;
create policy "Admins manage orders" on public.orders for all to authenticated using((select private.is_admin())) with check((select private.is_admin()));
drop policy if exists "Admins manage order items" on public.order_items;
create policy "Admins manage order items" on public.order_items for all to authenticated using((select private.is_admin())) with check((select private.is_admin()));
drop policy if exists "Admins manage payments" on public.payments;
create policy "Admins manage payments" on public.payments for all to authenticated using((select private.is_admin())) with check((select private.is_admin()));
drop policy if exists "Admins read stock movements" on public.stock_movements;
create policy "Admins read stock movements" on public.stock_movements for select to authenticated using((select private.is_admin()));
drop policy if exists "Admins insert stock movements" on public.stock_movements;
create policy "Admins insert stock movements" on public.stock_movements for insert to authenticated with check((select private.is_admin()));
drop policy if exists "Admins read admin users" on public.admin_users;
create policy "Admins read admin users" on public.admin_users for select to authenticated using(user_id=(select auth.uid()) or (select private.is_admin()));
drop policy if exists "Admins manage coupons" on public.coupons;
create policy "Admins manage coupons" on public.coupons for all to authenticated using((select private.is_admin())) with check((select private.is_admin()));

revoke all on public.orders,public.order_items,public.payments,public.stock_movements,public.admin_users,public.coupons from anon;
grant select on public.products to anon,authenticated;
