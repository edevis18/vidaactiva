create or replace function public.create_store_order(
 p_customer_name text,p_customer_phone text,p_customer_email text,p_customer_address text,
 p_notes text,p_items jsonb,p_idempotency_key uuid
) returns jsonb language plpgsql security definer set search_path=''
as $$
declare v_order_id uuid; v_subtotal numeric(12,2):=0; v_item record; v_product public.products%rowtype; v_unit_price numeric(12,2);
begin
 if nullif(trim(p_customer_name),'') is null or nullif(trim(p_customer_phone),'') is null or nullif(trim(p_customer_address),'') is null then raise exception 'Nombre, teléfono y dirección son obligatorios'; end if;
 if p_idempotency_key is null or jsonb_typeof(p_items)<>'array' or jsonb_array_length(p_items)=0 or jsonb_array_length(p_items)>100 then raise exception 'Pedido inválido'; end if;
 select id into v_order_id from public.orders where idempotency_key=p_idempotency_key;
 if v_order_id is not null then return jsonb_build_object('order_id',v_order_id,'message','Pedido ya registrado'); end if;
 for v_item in select x.product_id,sum(x.quantity)::integer quantity from jsonb_to_recordset(p_items) as x(product_id text,quantity integer) group by x.product_id loop
  if v_item.product_id is null or v_item.quantity is null or v_item.quantity<1 or v_item.quantity>99 then raise exception 'Cantidad o producto inválido'; end if;
  select * into v_product from public.products where id=v_item.product_id and active=true;
  if not found then raise exception 'Producto no disponible: %',v_item.product_id; end if;
  if v_product.stock<v_item.quantity then raise exception 'Stock insuficiente para % (disponible: %)',v_product.product_name,v_product.stock; end if;
  v_unit_price:=round(v_product.base_price*2.0,2); v_subtotal:=v_subtotal+(v_unit_price*v_item.quantity);
 end loop;
 insert into public.orders(customer_name,customer_phone,customer_email,customer_address,notes,subtotal,total,idempotency_key)
 values(trim(p_customer_name),trim(p_customer_phone),nullif(trim(p_customer_email),''),trim(p_customer_address),nullif(trim(p_notes),''),v_subtotal,v_subtotal,p_idempotency_key) returning id into v_order_id;
 for v_item in select x.product_id,sum(x.quantity)::integer quantity from jsonb_to_recordset(p_items) as x(product_id text,quantity integer) group by x.product_id loop
  select * into v_product from public.products where id=v_item.product_id and active=true;
  v_unit_price:=round(v_product.base_price*2.0,2);
  insert into public.order_items(order_id,product_id,product_name,quantity,unit_price,line_total) values(v_order_id,v_product.id,v_product.product_name,v_item.quantity,v_unit_price,v_unit_price*v_item.quantity);
 end loop;
 return jsonb_build_object('order_id',v_order_id,'order_number',(select order_number from public.orders where id=v_order_id),'status','pending_payment','total',v_subtotal);
end; $$;
revoke all on function public.create_store_order(text,text,text,text,text,jsonb,uuid) from public,anon,authenticated;
grant execute on function public.create_store_order(text,text,text,text,text,jsonb,uuid) to service_role;

create or replace function private.can_upload_payment_proof(p_order_id uuid)
returns boolean language sql stable security definer set search_path=''
as $$ select exists(select 1 from public.orders o where o.id=p_order_id and o.status in ('pending_payment','payment_rejected')); $$;
grant usage on schema private to anon;
grant execute on function private.can_upload_payment_proof(uuid) to anon,authenticated;

insert into storage.buckets(id,name,public,file_size_limit,allowed_mime_types)
values('payment-proofs','payment-proofs',false,8388608,array['image/jpeg','image/png','image/webp','application/pdf'])
on conflict(id) do update set public=false,file_size_limit=8388608,allowed_mime_types=excluded.allowed_mime_types;
drop policy if exists "Customers upload payment proofs" on storage.objects;
create policy "Customers upload payment proofs" on storage.objects for insert to anon,authenticated
with check(bucket_id='payment-proofs' and (storage.foldername(name))[1] ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$' and private.can_upload_payment_proof(((storage.foldername(name))[1])::uuid));
drop policy if exists "Admins read payment proofs" on storage.objects;
create policy "Admins read payment proofs" on storage.objects for select to authenticated using(bucket_id='payment-proofs' and (select private.is_admin()));

create or replace function public.submit_payment_proof(p_order_id uuid,p_reference text,p_proof_url text default null)
returns uuid language plpgsql security definer set search_path=''
as $$
declare v_payment_id uuid;
begin
 if nullif(trim(p_reference),'') is null then raise exception 'Referencia de pago obligatoria'; end if;
 if nullif(trim(p_proof_url),'') is null or split_part(p_proof_url,'/',1)<>p_order_id::text then raise exception 'Debes adjuntar el comprobante del pedido'; end if;
 if not exists(select 1 from storage.objects so where so.bucket_id='payment-proofs' and so.name=p_proof_url) then raise exception 'No se encontró el archivo del comprobante'; end if;
 if not exists(select 1 from public.orders o where o.id=p_order_id and o.status in ('pending_payment','payment_rejected')) then raise exception 'Pedido no encontrado o no admite comprobantes'; end if;
 insert into public.payments(order_id,reference,proof_url,status) values(p_order_id,trim(p_reference),p_proof_url,'submitted') returning id into v_payment_id;
 update public.orders set status='payment_under_review',updated_at=now() where id=p_order_id;
 return v_payment_id;
end; $$;
revoke all on function public.submit_payment_proof(uuid,text,text) from public,anon,authenticated;
grant execute on function public.submit_payment_proof(uuid,text,text) to service_role;

create or replace function public.admin_adjust_stock(p_product_id text,p_new_stock integer,p_note text default null)
returns jsonb language plpgsql security invoker set search_path=''
as $$
declare v_product public.products%rowtype; v_delta integer;
begin
 if not exists(select 1 from public.admin_users a where a.user_id=(select auth.uid())) then raise exception 'No autorizado'; end if;
 if p_new_stock is null or p_new_stock<0 then raise exception 'Stock inválido'; end if;
 select * into v_product from public.products where id=p_product_id for update;
 if not found then raise exception 'Producto no encontrado'; end if;
 v_delta:=p_new_stock-v_product.stock;
 update public.products set stock=p_new_stock,updated_at=now() where id=p_product_id returning * into v_product;
 if v_delta<>0 then insert into public.stock_movements(product_id,movement_type,quantity_change,stock_after,note,created_by) values(p_product_id,'adjustment',v_delta,v_product.stock,coalesce(p_note,'Ajuste desde panel administrativo'),(select auth.uid())); end if;
 return jsonb_build_object('product_id',p_product_id,'stock',v_product.stock);
end; $$;
grant execute on function public.admin_adjust_stock(text,integer,text) to authenticated;

create or replace function public.confirm_store_payment(p_order_id uuid,p_payment_id uuid default null)
returns jsonb language plpgsql security invoker set search_path=''
as $$
declare v_item record; v_product public.products%rowtype; v_order public.orders%rowtype;
begin
 if not exists(select 1 from public.admin_users a where a.user_id=(select auth.uid())) then raise exception 'No autorizado'; end if;
 select * into v_order from public.orders where id=p_order_id for update;
 if not found then raise exception 'Pedido no encontrado'; end if;
 if v_order.status='paid_confirmed' then return jsonb_build_object('order_id',p_order_id,'status','paid_confirmed','message','El pedido ya fue confirmado'); end if;
 if v_order.status not in ('pending_payment','payment_under_review','stock_issue') then raise exception 'El pedido no puede confirmarse desde su estado actual'; end if;
 if p_payment_id is not null and not exists(select 1 from public.payments p where p.id=p_payment_id and p.order_id=p_order_id and p.status='submitted') then raise exception 'Pago no válido o ya procesado'; end if;
 for v_item in select product_id,quantity from public.order_items where order_id=p_order_id order by product_id loop
  select * into v_product from public.products where id=v_item.product_id for update;
  if not found or v_product.stock<v_item.quantity then update public.orders set status='stock_issue',updated_at=now() where id=p_order_id; return jsonb_build_object('order_id',p_order_id,'status','stock_issue','message','Stock insuficiente; no se descontó ninguna unidad'); end if;
 end loop;
 for v_item in select product_id,quantity from public.order_items where order_id=p_order_id order by product_id loop
  update public.products set stock=stock-v_item.quantity,updated_at=now() where id=v_item.product_id returning * into v_product;
  insert into public.stock_movements(product_id,order_id,movement_type,quantity_change,stock_after,note,created_by) values(v_item.product_id,p_order_id,'sale',-v_item.quantity,v_product.stock,'Descuento por pago verificado',(select auth.uid()));
 end loop;
 update public.orders set status='paid_confirmed',confirmed_at=now(),updated_at=now() where id=p_order_id;
 if p_payment_id is not null then update public.payments set status='verified',reviewed_by=(select auth.uid()),reviewed_at=now() where id=p_payment_id; end if;
 return jsonb_build_object('order_id',p_order_id,'status','paid_confirmed');
end; $$;
grant execute on function public.confirm_store_payment(uuid,uuid) to authenticated;

